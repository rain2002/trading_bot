import yfinance as yf
import pandas as pd
import pandas_ta as ta
import sqlite3
import os

# Database file for the virtual wallet
DB_NAME = 'trading_bot.db'

def initialize_wallet():
    """Initializes a virtual wallet using SQLite with $10,000 USD."""
    conn = sqlite3.connect(DB_NAME)
    cursor = conn.cursor()
    
    cursor.execute('''
        CREATE TABLE IF NOT EXISTS wallet (
            id INTEGER PRIMARY KEY,
            balance REAL NOT NULL,
            currency TEXT NOT NULL
        )
    ''')
    
    cursor.execute('SELECT balance FROM wallet WHERE currency = "USD"')
    result = cursor.fetchone()
    
    if not result:
        cursor.execute('INSERT INTO wallet (balance, currency) VALUES (?, ?)', (10000.0, 'USD'))
        conn.commit()
        print("Virtual wallet initialized with an initial balance of $10,000 USD.")
    else:
        print(f"Virtual wallet loaded. Current balance: ${result[0]:.2f} USD")
        
    conn.close()

def fetch_market_data(symbol='SPY', period='5y', interval='1d'):
    """
    Fetches historical data using yfinance and calculates robust statistical indicators.
    Increased default period to 5 years to ensure plenty of data for ML training
    after dropping the 200 days required for the 200-SMA.
    """
    print(f"Fetching data for {symbol} with {interval} interval over {period}...")
    
    ticker = yf.Ticker(symbol)
    df = ticker.history(period=period, interval=interval)
    
    if df.empty:
        print("No data found. Please check the symbol or date range.")
        return df

    df = df.reset_index()
    
    if 'Datetime' in df.columns:
        df.rename(columns={'Datetime': 'timestamp'}, inplace=True)
    elif 'Date' in df.columns:
        df.rename(columns={'Date': 'timestamp'}, inplace=True)
        
    df.columns = [col.lower() for col in df.columns]

    # --- Feature Engineering: Technical & Statistical Indicators ---
    # We select a diverse set of indicators representing different market dynamics 
    # to feed into our future ML model without creating noisy, highly correlated features.
    
    # 1. Trend: MACD & Moving Averages (50 & 200 for Golden Cross)
    df.ta.macd(append=True)
    df.ta.sma(length=50, append=True)
    df.ta.sma(length=200, append=True)
    
    # 2. Momentum / Mean Reversion: RSI (Relative Strength Index)
    df.ta.rsi(length=14, append=True)
    
    # 3. Volatility: Bollinger Bands (2 Standard Deviations)
    df.ta.bbands(length=20, std=2, append=True)
    
    # 4. Statistical Arbitrage Proxy: Z-Score of Close Price (20-day rolling)
    # How far is the current price from the 20-day mean in terms of standard deviations?
    rolling_mean = df['close'].rolling(window=20).mean()
    rolling_std = df['close'].rolling(window=20).std()
    df['z_score_20'] = (df['close'] - rolling_mean) / rolling_std
    
    # Drop rows with NaN values generated by the rolling windows (first 200 days will be dropped)
    df.dropna(inplace=True)
    
    return df

if __name__ == '__main__':
    initialize_wallet()
    
    # Fetch 5 years of data for a solid ML training set
    df = fetch_market_data(symbol='SPY', period='5y', interval='1d')
    
    if not df.empty:
        print(f"\nSuccessfully generated {len(df)} days of data with engineered features.")
        print("\nRecent Market Data with Advanced Indicators:")
        # Displaying a subset of columns to keep the terminal output readable
        cols_to_show = ['timestamp', 'close', 'SMA_50', 'SMA_200', 'RSI_14', 'z_score_20']
        print(df[cols_to_show].tail(10))
        
        data_dir = 'data'
        os.makedirs(data_dir, exist_ok=True)
        csv_path = os.path.join(data_dir, 'historical_data.csv')
        df.to_csv(csv_path, index=False)
        
        print(f"\nData saved successfully to {csv_path} for future Machine Learning pipelines.")
